.include "asm/include/battle_commands.inc"

.data

_000:
    CompareVarToValue OPCODE_FLAG_SET, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_NO_BLINK, _016
    PlayMoveHitSound BATTLER_CATEGORY_MSG_TEMP
    FlickerMon BATTLER_CATEGORY_MSG_TEMP
    Wait 
    CompareVarToValue OPCODE_EQU, BSCRIPT_VAR_WAITING_BATTLERS, 0, _016
    Call BATTLE_SUBSCRIPT_TYPE_RESIST_BERRY

_016:
    UpdateHealthBar BATTLER_CATEGORY_MSG_TEMP
    Wait 
    UpdateHealthBarValue BATTLER_CATEGORY_MSG_TEMP
    TryFaintMon BATTLER_CATEGORY_MSG_TEMP
    CompareVarToValue OPCODE_GT, BSCRIPT_VAR_HP_CALC, 0, _end
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP_ASSURANCE_DAMAGE_MASK, BSCRIPT_VAR_HP_CALC

_confusion:
	CompareMonDataToValue OPCODE_FLAG_NOT, BATTLER_CATEGORY_ATTACKER, BMON_DATA_STATUS2, STATUS2_CONFUSION, _end
	CompareVarToVar OPCODE_EQU, BSCRIPT_VAR_BATTLER_ATTACKER, BSCRIPT_VAR_BATTLER_TARGET, _end
	CompareVarToValue OPCODE_FLAG_SET, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_NO_BLINK, _end
	CalcConfusionDamage
	UpdateVarFromVar OPCODE_ADD, BSCRIPT_VAR_CALC_TEMP, BSCRIPT_VAR_HP_CALC
	IfLastHitOfMultiHit _islasthit
	GoTo _end
	
_islasthit:
    CheckAbility CHECK_OPCODE_HAVE, BATTLER_CATEGORY_ATTACKER, ABILITY_ROCK_HEAD, _end
    CheckAbility CHECK_OPCODE_HAVE, BATTLER_CATEGORY_ATTACKER, ABILITY_MAGIC_GUARD, _end
    CompareVarToValue OPCODE_EQU, BSCRIPT_VAR_CALC_TEMP, 0, _end
    DivideVarByValue BSCRIPT_VAR_CALC_TEMP, 2
    UpdateHealthBar BATTLER_CATEGORY_ATTACKER
    Wait
    UpdateHealthBarValue BATTLER_CATEGORY_ATTACKER
    TryFaintMon BATTLER_CATEGORY_ATTACKER
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP_ASSURANCE_DAMAGE_MASK, BSCRIPT_VAR_CALC_TEMP
    // {0} is hit with recoil!
    PrintMessage 279, TAG_NICKNAME, BATTLER_CATEGORY_ATTACKER
    Wait 
    WaitButtonABTime 30
	
_end:
	UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_NO_BLINK
    End
